@pytest.fixture(scope="session")
def api_schema(contract_env: ContractEnv) -> Any:
    return schemathesis.openapi.from_dict(contract_env.env.app.openapi())


schema = schemathesis.pytest.from_fixture("api_schema")


@schema.parametrize()
@settings(
    max_examples=15,
    deadline=None,
    suppress_health_check=[
        HealthCheck.too_slow,
        HealthCheck.filter_too_much,
        HealthCheck.function_scoped_fixture,
    ],
)
def test_api_conforms_to_openapi(case: Any, contract_env: ContractEnv) -> None:
    kwargs = case.as_transport_kwargs(base_url="http://api")
    response = contract_env.send(kwargs)
    # ignored_auth replays the request itself (over requests); the 401 test below covers every operation
    # positive_data_acceptance: schema-valid input can still fail semantic rules with 422 by design
    # (valid_to after valid_from, opaque cursors, the test-split triage rule); negative_data_rejection stays on
    case.validate_response(response, excluded_checks=[ignored_auth, positive_data_acceptance])


def test_every_v1_operation_requires_a_token(contract_env: ContractEnv) -> None:
    spec = contract_env.env.app.openapi()
    checked = 0
    for path, ops in spec["paths"].items():
        if not path.startswith("/v1/"):
            continue
        url = path.replace("{", "").replace("}", "")
        for method in ops:
            response = contract_env.send({"method": method.upper(), "url": url}, auth=False)
            assert response.status_code == 401, (method, path, response.status_code)
            assert response.headers["content-type"].startswith("application/problem+json")
            assert response.headers["www-authenticate"] == "Bearer"
            checked += 1
    assert checked >= 16


