"""Eval summary (`evals/reports/latest.json`) and `evals/REPORT.md`, rendered from run reports only.

Every number here is copied from an ``evalgate.report.v1`` report (or the ablation/red-team JSON written by
their scripts); nothing is computed beyond per-category means of per-case scores.
"""

from __future__ import annotations

from typing import Any

from evalgate.report import render_markdown

PRIMARY = "rag"
CATEGORY_METRICS = ("recall@10", "key_fact_accuracy", "abstention_accuracy")


def _key(report: dict[str, Any], name: str, unit: str) -> str:
    key = f"{name}_ms" if unit == "ms" and not name.endswith("_ms") else name
    return key if report["suite"] == PRIMARY else f"{report['suite']}.{key}"


def _without_cases(report: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in report.items() if k != "cases"}


def by_category(
    report: dict[str, Any], metrics: list[str] | tuple[str, ...] = CATEGORY_METRICS
) -> dict[str, dict[str, Any]]:
    """Mean per-case score per question category (the case id prefix, e.g. ``single_hop``)."""
    cats: dict[str, dict[str, list[float]]] = {}
    counts: dict[str, int] = {}
    for case in report.get("cases", []):
        if case.get("error"):
            continue
        cat = case["id"].rsplit("-", 1)[0]
        counts[cat] = counts.get(cat, 0) + 1
        bucket = cats.setdefault(cat, {m: [] for m in metrics})
        for m in metrics:
            value = case["scores"].get(m)
            if isinstance(value, int | float):
                bucket[m].append(float(value))
    return {
        cat: {"n": counts[cat]} | {m: (sum(v) / len(v) if v else None) for m, v in values.items()}
        for cat, values in sorted(cats.items())
    }


def summarize(
    reports: list[dict[str, Any]],
    *,
    ablation: list[dict[str, Any]] | None = None,
    redteam: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """The `GET /v1/evals/latest` document: flattened metric values plus the slim suite reports."""
    metrics: dict[str, float | None] = {}
    for report in reports:
        for name, m in report["metrics"].items():
            metrics[_key(report, name, m["unit"])] = m["value"]
    primary = next((r for r in reports if r["suite"] == PRIMARY), reports[0])
    present = [m for m in CATEGORY_METRICS if m in primary["metrics"]]
    return {
        "generated_at": max(r["generated_at"] for r in reports),
        "split": primary["split"],
        "llm": primary.get("target", {}).get("llm", "unknown"),
        "passed": all(r["passed"] for r in reports),
        "metrics": metrics,
        "ablation": ablation or [],
        "redteam": redteam,
        "by_category": {"suite": primary["suite"], "rows": by_category(primary, present)},
        "suites": {r["suite"]: _without_cases(r) for r in reports},
    }


def slim_baseline(reports: list[dict[str, Any]]) -> dict[str, Any]:
    """Combined baseline for ``evalgate check``: one slim report per suite, keyed by suite name."""
    return {r["suite"]: _without_cases(r) for r in reports}


def _num(value: Any, ms: bool = False) -> str:
    if value is None:
        return "n/a"
    return f"{value:.0f} ms" if ms else f"{value:.3f}"


PREFACE = """\
Generated by `make eval` (`scripts/run_evals.py`) from the latest run; do not edit by hand.

**Offline numbers.** Answers are produced by the deterministic FakeLLM with the LSA embedder and the
feature reranker (`llm` below). They measure the deterministic pipeline (retrieval, ACL, validity,
citation verification, abstention), not the quality of a live model; live numbers come from
`make eval-live` and are not in this report. Thresholds are from BUILD.md §11; tuning used the dev split
only, and the numbers below are on the split named in each suite."""


def render_report(latest: dict[str, Any], *, failures: list[str]) -> str:
    suites = list(latest["suites"].values())
    text = render_markdown(suites, title="Evaluation report", preface=PREFACE)
    lines = [text.rstrip(), "", "## Gate", ""]
    if failures:
        lines += [f"- FAIL {f}" for f in failures]
    else:
        lines.append("All gates pass (thresholds and no regression beyond 1.0 pp against the baseline).")

    cats = latest.get("by_category") or {}
    rows = cats.get("rows") or {}
    if rows:
        names = [k for k in next(iter(rows.values())) if k != "n"]
        lines += [
            "",
            f"## By question category (`{cats['suite']}`)",
            "",
            "| Category | Cases | " + " | ".join(names) + " |",
            "|---|---|" + "---|" * len(names),
        ]
        for cat, row in rows.items():
            lines.append(f"| {cat} | {row['n']} | " + " | ".join(_num(row[n]) for n in names) + " |")

    lines += ["", "## Retrieval ablation", ""]
    ablation = latest.get("ablation") or []
    if ablation:
        cols = [k for k in ablation[0] if k != "config"]
        lines += ["| Configuration | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
        for row in ablation:
            cells = [_num(row.get(c), ms=c.endswith("_ms")) for c in cols]
            lines.append(f"| {row['config']} | " + " | ".join(cells) + " |")
    else:
        lines.append("Not run yet: `make eval-ablation` adds this table.")

    lines += ["", "## Red-team", ""]
    redteam = latest.get("redteam")
    if redteam:
        lines.append(f"{redteam['total']} attacks, {redteam['failures']} failures (`make redteam`).")
    else:
        lines.append("Not run yet: `make redteam` adds this section.")
    return "\n".join(lines) + "\n"
